"""A worked example of a dossier, for showing the output shape before a live run.

The evidence board is the product. Until a Parallel credential is attached, no
visitor can see one, which means the most important screen is invisible exactly
when someone is deciding whether the project is any good.

This builds one. Three rules make it honest:

1. **It is about a fragment that does not exist.** The subject is the invented
   frame illustrated on the landing page — "Tell Mara the lamp still burns" —
   and the candidate is a made-up 1921 title. No real film is described, so no
   real film can be misattributed by it.

2. **Every source is an RFC 2606 reserved domain** (`example.org`, `example.com`).
   These can never resolve to a real page. A reader who checks a citation finds
   a placeholder, which is the correct answer.

3. **It runs through the real code.** The same `build_evidence` and the same
   `IdentityGate` that serve a live investigation produce this result, so the
   verdict and every threshold below are genuinely computed rather than typed
   out. If the schema or the gate changes, this example changes with it or the
   tests fail. It cannot drift into being a picture of something the software
   no longer does.

The response is marked `example: true` at every level, and the UI renders it
behind a sticky banner it cannot scroll away from.
"""

