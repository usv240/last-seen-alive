DISCLAIMER = (
    "Worked example. This is not a real investigation: the fragment is invented, "
    "the candidate film does not exist, and every source is an RFC 2606 reserved "
    "domain that can never resolve. It is generated by the same evidence builder "
    "and the same deterministic gate that serve a live run, so the shape and the "
    "thresholds are real even though the evidence is not."
)

